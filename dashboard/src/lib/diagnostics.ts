import type { ErrorInfo } from 'react';

/**
 * Diagnostic helpers for the global error boundary.
 *
 * Everything produced here is intended to be safe to paste into a bug report:
 * wallet addresses, private keys, tokens and URL credentials are masked before
 * a report is copied to the clipboard or sent to a configured collector.
 */

export const REDACTED = '[REDACTED]';

export interface DiagnosticReport {
  timestamp: string;
  message: string;
  stack: string | null;
  componentStack: string | null;
  userAgent: string;
  url: string;
  sessionId: string;
}

export interface DiagnosticContext {
  /** Injectable for deterministic tests; defaults to the current time. */
  timestamp?: string;
  userAgent?: string;
  url?: string;
  sessionId?: string;
}

const SENSITIVE_KEY =
  '(?:private[_-]?key|privkey|secret(?:[_-]?key)?|seed|mnemonic|password|passwd|authorization|auth|api[_-]?key|access[_-]?token|refresh[_-]?token|session(?:[_-]?(?:id|token))?|token)';

const REDACTION_RULES: ReadonlyArray<{ pattern: RegExp; replacement: string }> = [
  {
    pattern: /-----BEGIN (?:[A-Z ]+ )?PRIVATE KEY-----[\s\S]*?-----END (?:[A-Z ]+ )?PRIVATE KEY-----/g,
    replacement: REDACTED,
  },
  {
    // JSON Web Tokens always start with an encoded JSON header ("eyJ").
    pattern: /\beyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\b/g,
    replacement: REDACTED,
  },
  {
    // Handle "Bearer …" before generic key=value pairs so the token itself is
    // not left behind after the key has been masked.
    pattern: /\bBearer\s+[A-Za-z0-9._~+/=-]+/gi,
    replacement: `Bearer ${REDACTED}`,
  },
  {
    // key=value / key: value pairs, e.g. token=..., "privateKey": ...
    pattern: new RegExp(`\\b(${SENSITIVE_KEY})\\s*[:=]\\s*["']?[^\\s"',;&}\\)\\]]+`, 'gi'),
    replacement: `$1=${REDACTED}`,
  },
  {
    // Correlation ids generated by this app use the "sid-" prefix.
    pattern: /\bsid-[A-Za-z0-9_-]{8,}\b/g,
    replacement: `sid-${REDACTED}`,
  },
  {
    pattern: /\b0x[a-fA-F0-9]{64}\b/g,
    replacement: REDACTED,
  },
  {
    pattern: /\b0x[a-fA-F0-9]{40}\b/g,
    replacement: REDACTED,
  },
  {
    // Stellar strkeys: G… account, S… secret seed, C… contract id.
    pattern: /\b[GSC][2-7A-Z]{55}\b/g,
    replacement: REDACTED,
  },
  {
    pattern: /\bAKIA[0-9A-Z]{16}\b/g,
    replacement: REDACTED,
  },
];

/** Mask anything that could identify a wallet or authenticate a session. */
export function redactSensitiveData(value: string | null | undefined): string {
  if (!value) return '';
  return REDACTION_RULES.reduce(
    (text, { pattern, replacement }) => text.replace(pattern, replacement),
    String(value),
  );
}

/** Keep only the origin and path: query strings and fragments often carry tokens. */
export function sanitizeUrl(value: string | null | undefined): string {
  if (!value) return '';
  try {
    const parsed = new URL(value);
    return redactSensitiveData(`${parsed.origin}${parsed.pathname}`);
  } catch {
    return redactSensitiveData(value);
  }
}

/** Short-lived, local correlation id only — never an application auth token. */
export function getSessionId(): string {
  try {
    let id = sessionStorage.getItem('ap-session-id');
    if (!id) {
      id = `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
      sessionStorage.setItem('ap-session-id', id);
    }
    return redactSensitiveData(id);
  } catch {
    return 'unknown-session';
  }
}

export function buildDiagnosticReport(
  error: Error | null,
  errorInfo: ErrorInfo | null,
  context: DiagnosticContext = {},
): DiagnosticReport {
  const message = error ? error.message || String(error) : 'Unknown error';

  return {
    timestamp: context.timestamp ?? new Date().toISOString(),
    message: redactSensitiveData(message),
    stack: error?.stack ? redactSensitiveData(error.stack) : null,
    componentStack: errorInfo?.componentStack ? redactSensitiveData(errorInfo.componentStack) : null,
    userAgent: redactSensitiveData(
      context.userAgent ?? (typeof navigator === 'undefined' ? '' : navigator.userAgent),
    ),
    url: sanitizeUrl(context.url ?? (typeof window === 'undefined' ? '' : window.location.href)),
    sessionId: context.sessionId !== undefined
      ? redactSensitiveData(context.sessionId) || 'unknown-session'
      : getSessionId(),
  };
}

/** Human-readable bundle shown to the user and copied to the clipboard. */
export function formatDiagnosticReport(report: DiagnosticReport): string {
  return [
    '--- AnchorPoint Diagnostic Report (anonymized) ---',
    `Timestamp (timestamp): ${report.timestamp}`,
    `URL (url): ${report.url}`,
    `User Agent (userAgent): ${report.userAgent || 'unknown'}`,
    `Session ID (sessionId): ${report.sessionId}`,
    `Message (message): ${report.message}`,
    'Stack (stack):',
    report.stack ?? 'Not available',
    'Component Stack (componentStack):',
    report.componentStack ?? 'Not available',
    '--- End Diagnostic Report ---',
  ].join('\n');
}
